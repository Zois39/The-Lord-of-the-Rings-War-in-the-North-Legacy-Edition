# Падежный движок русских имён предметов (генитив для постмодификаторов)
import re
ADJ_GEN=[(r'ий$','его'),(r'ый$','ого'),(r'ой$','ого'),(r'ая$','ой'),(r'яя$','ей'),(r'ое$','ого'),(r'ее$','его'),(r'ые$','ых'),(r'ие$','их')]
def adj_gen(w):
    for p,r in ADJ_GEN:
        if re.search(p,w): return re.sub(p,r,w)
    return w
def noun_gen(w):
    if re.search(r'[бвгджзклмнпрстфхцчшщ]$',w): return w+'а'
    if re.search(r'[ая]н$',w): return w+'а'
    if w.endswith('й'): return w[:-1]+'я'
    if re.search(r'[жшчщц]а$',w): return w[:-1]+'и'
    if w.endswith('а'): return w[:-1]+'ы'
    if w.endswith('я'): return w[:-1]+'и'
    if w.endswith('ь'): return w[:-1]+'и'
    return w
EXC={'Эпоха':'Эпохи','Мория':'Мории','Лориэн':'Лориэна','Эребор':'Эребора','Рохан':'Рохана','Гондор':'Гондора','Арнор':'Арнора','Ангмар':'Ангмара','Мордор':'Мордора','Изенгард':'Изенгарда','Белерианд':'Белерианда','Дум':'Дума','Карн':'Карна','Эред':'Эреда','Казад':'Казада','Митрин':'Митрина','Гундабад':'Гундабада','Нординбад':'Нординбада','Ривенделл':'Ривенделла','Лихолесье':'Лихолесья','Трандуил':'Трандуила','Галадриэль':'Галадриэль','Гимли':'Гимли','Леголас':'Леголаса'}
def word_gen(w):
    if w in EXC: return EXC[w]
    if re.search(r'(ий|ый|ой|ая|яя|ое|ее|ые|ие)$',w): return adj_gen(w)
    return noun_gen(w)
